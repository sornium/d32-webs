export function applyDocumentLanguage(lang: string) {
  if (typeof document === 'undefined') return;
  const clean = (lang || 'EN').toUpperCase();
  const meta = SUPPORTED_LANGUAGES.find((l) => l.code === clean) || SUPPORTED_LANGUAGES[0];
  document.documentElement.lang = meta.code.toLowerCase();
  document.documentElement.dir = meta.dir;
}

export function t(key: string, defaultValue?: string): string {
  const { language } = useStore.getState();
  const langKey = language?.toUpperCase() || 'EN';
  const str = translations[langKey]?.[key];
  if (str) return str;
  // Fallback to English translation before defaulting
  const enStr = translations.EN?.[key];
  return enStr || defaultValue || key;
}

export function useTranslation() {
  const { language, setLanguage } = useStore();
  const langKey = language?.toUpperCase() || 'EN';

  return {
    language: langKey,
    setLanguage: (lang: string) => {
      setLanguage(lang);
      applyDocumentLanguage(lang);
    },
    t: (key: string, defaultValue?: string) => {
      const str = translations[langKey]?.[key];
      if (str) return str;
      const enStr = translations.EN?.[key];
      return enStr || defaultValue || key;
    },
    isRTL: langKey === 'AR',
  };
}
